if (!function_exists('mzf_register_acf_form_definitions')) {
    function mzf_register_acf_form_definitions(): void
    {
        if (function_exists('acf_add_local_internal_post_type')) {
            acf_add_local_internal_post_type(mzf_get_form_post_type_definition(), 'acf-post-type');
        }

        if (function_exists('acf_add_local_field_group')) {
            acf_add_local_field_group(mzf_get_form_field_group_definition());
        }
    }
}
add_action('acf/init', 'mzf_register_acf_form_definitions', 5);
