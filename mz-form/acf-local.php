if (!function_exists('mzf_register_form_post_type_fallback')) {
    function mzf_register_form_post_type_fallback(): void
    {
        if (post_type_exists('form')) {
            return;
        }

        register_post_type('form', mzf_get_form_post_type_args());
    }
}
add_action('init', 'mzf_register_form_post_type_fallback', 1);

